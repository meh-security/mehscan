"""Render the worker API reference from the same catalog used by the runtime."""
import argparse
from pathlib import Path
import review_context as context


def render(skill):
    api = context.research_api(skill)
    lines = ["# Worker review API", "", "<!-- Generated by scripts/review_api_docs.py; edit review-api.json and guidance-index.json. -->", "",
        "This is the model's bounded research API, not the full operator CLI.",
        "The controller supplies its typed schema and remaining budgets each turn.",
        "For scans, plans, finalization and reports use [commands](commands.md).", "",
        api["common"], "", "| Tool | Arguments | Units | Purpose and limits |", "| --- | --- | ---: | --- |"]
    for tool in api["tools"]:
        arguments = ", ".join(tool["required"] + ["optional " + name for name in tool["optional"]])
        lines.append("| `" + tool["name"] + "` | " + arguments + " | " + str(tool["query_units"]) + " | " + tool["description"] + " " + tool["semantics"] + " |")
    lines += ["", "## Additional guidance", "", "Read the relevant file in manual mode. In worker mode, request", "`guidance(name)` using the exact offered name. Load only what changes this", "review; never cite a guide as application evidence.", "", "| Name | Read when |", "| --- | --- |"]
    for name, guide in context.guidance_catalog(skill).items():
        lines.append("| [`" + name + "`](" + guide["path"] + ") | " + guide["when"] + " |")
    lines += ["", "A research reply has `action=research`, a nonempty `research` array and", "`draft=null`. A final reply has `action=final`, `research=[]` and the complete", "draft. Keep the selected operation, progress and remaining questions explicit.", "The controller validates protocol and source bindings; it does not certify", "the model's security interpretation.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--skill-root", type=Path, default=Path(__file__).resolve().parents[1] / "skills/mehscan-security")
    args = parser.parse_args()
    path = args.skill_root / "references/worker-api.md"
    text = render(args.skill_root)
    if args.check:
        if path.read_text(encoding="utf-8") != text:
            parser.exit(1, "worker-api.md differs from its runtime catalogs; regenerate it\n")
    else:
        path.write_text(text, encoding="utf-8")
