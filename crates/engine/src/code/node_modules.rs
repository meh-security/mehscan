//! Shared application module identity. Resolve files, never execute project code
//! or analyze installed dependencies. Only selected source files can be targets.
use ast_grep_core::{AstGrep, Node, tree_sitter::StrDoc};
use ast_grep_language::SupportLang;
use mehscan_core::Language;
use oxc_resolver::{ResolveOptions, Resolver, TsconfigOptions, TsconfigReferences};
use serde_json::Value;
use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
    sync::Mutex,
};

#[derive(Clone, Copy, Debug, Default, Eq, PartialEq, Ord, PartialOrd)]
pub(crate) enum ImportMode {
    #[default]
    Import,
    Require,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub(crate) enum ModuleTarget {
    Source(String),
    External(String),
    Unresolved(String),
}

#[derive(Clone, Debug, Eq, PartialEq, Ord, PartialOrd)]
pub(crate) struct ExportTarget {
    pub path: String,
    pub name: String,
}

#[derive(Clone, Debug)]
struct Workspace {
    directory: String,
    exports: bool,
}
#[derive(Clone, Debug)]
struct ExportEdge {
    module: Option<String>,
    name: String,
    mode: ImportMode,
}
#[derive(Debug, Default)]
struct Exports {
    named: BTreeMap<String, ExportEdge>,
    stars: Vec<String>,
    instance_methods: BTreeMap<String, BTreeSet<String>>,
}

#[derive(Debug, Default)]
pub(crate) struct NodeModuleIndex {
    root: Option<PathBuf>,
    files: BTreeSet<String>,
    workspaces: BTreeMap<String, Option<Workspace>>,
    exports: BTreeMap<String, Exports>,
    configs: BTreeMap<String, Option<String>>,
    resolvers: BTreeMap<(Option<String>, ImportMode), Resolver>,
    cache: Mutex<BTreeMap<(String, String, ImportMode), ModuleTarget>>,
    export_cache: Mutex<BTreeMap<(String, String), Option<ExportTarget>>>,
    export_failures: Mutex<BTreeSet<String>>,
}

pub(crate) fn module_key(path: &str) -> String {
    let path = path.replace('\\', "/");
    let path = path.trim_start_matches("./");
    [".tsx", ".jsx", ".mts", ".cts", ".mjs", ".cjs", ".ts", ".js"]
        .iter()
        .find_map(|extension| path.strip_suffix(extension))
        .unwrap_or(path)
        .to_string()
}

impl NodeModuleIndex {
    pub(crate) fn build<'a>(
        root: Option<&Path>,
        sources: impl Iterator<Item = (&'a str, Language, &'a str)>,
        metadata: impl Iterator<Item = &'a str>,
    ) -> Self {
        Self::build_inner(root, sources, metadata, true)
    }

    /// Reviewer file lookup needs package/config resolution, not another AST
    /// pass over the repository. Export summaries are built only for scanning.
    pub(crate) fn file_index<'a>(
        root: Option<&Path>,
        sources: impl Iterator<Item = (&'a str, Language, &'a str)>,
        metadata: impl Iterator<Item = &'a str>,
    ) -> Self {
        Self::build_inner(root, sources, metadata, false)
    }

    fn build_inner<'a>(
        root: Option<&Path>,
        sources: impl Iterator<Item = (&'a str, Language, &'a str)>,
        metadata: impl Iterator<Item = &'a str>,
        parse_exports: bool,
    ) -> Self {
        let sources = sources
            .filter(|(_, l, _)| {
                matches!(
                    l,
                    Language::Javascript | Language::Typescript | Language::Tsx
                )
            })
            .collect::<Vec<_>>();
        if sources.is_empty() {
            return Self::default();
        }
        let mut index = Self {
            root: root.and_then(|p| {
                std::fs::canonicalize(if p.is_file() {
                    p.parent().unwrap_or(p)
                } else {
                    p
                })
                .ok()
            }),
            ..Self::default()
        };
        index
            .files
            .extend(sources.iter().map(|(p, _, _)| p.replace('\\', "/")));
        if let Some(root) = index.root.clone() {
            let mut manifests = BTreeSet::from(["package.json".to_string()]);
            manifests.extend(
                metadata
                    .filter(|p| {
                        Path::new(p)
                            .file_name()
                            .is_some_and(|n| n == "package.json")
                    })
                    .map(str::to_string),
            );
            // Also works for selected/single-file inputs without a metadata ledger.
            for file in &index.files {
                let mut directory = Path::new(file).parent();
                while let Some(path) = directory {
                    manifests.insert(
                        path.join("package.json")
                            .to_string_lossy()
                            .replace('\\', "/"),
                    );
                    directory = path.parent();
                }
            }
            let manifests = manifests
                .into_iter()
                .filter_map(|path| read_json(&root.join(&path)).map(|json| (path, json)))
                .collect::<BTreeMap<_, _>>();
            let mut patterns = Vec::new();
            if let Some(package) = manifests.get("package.json") {
                let workspaces = package
                    .get("workspaces")
                    .and_then(|v| v.as_array().or_else(|| v.get("packages")?.as_array()));
                patterns.extend(
                    workspaces
                        .into_iter()
                        .flatten()
                        .filter_map(Value::as_str)
                        .map(str::to_string),
                );
            }
            if let Ok(text) = std::fs::read_to_string(root.join("pnpm-workspace.yaml"))
                && text.len() <= 1024 * 1024
                && let Ok(value) = serde_yaml::from_str::<serde_yaml::Value>(&text)
            {
                patterns.extend(
                    value
                        .get("packages")
                        .and_then(|v| v.as_sequence())
                        .into_iter()
                        .flatten()
                        .filter_map(|v| v.as_str())
                        .map(str::to_string),
                );
            }
            for (path, manifest) in manifests {
                let directory = Path::new(&path)
                    .parent()
                    .unwrap_or(Path::new(""))
                    .to_string_lossy()
                    .replace('\\', "/");
                if !directory.is_empty() && !workspace_matches(&directory, &patterns) {
                    continue;
                }
                let Some(name) = manifest.get("name").and_then(Value::as_str) else {
                    continue;
                };
                let workspace = Workspace {
                    directory,
                    exports: manifest.get("exports").is_some(),
                };
                index
                    .workspaces
                    .entry(name.to_string())
                    .and_modify(|w| *w = None)
                    .or_insert(Some(workspace));
            }
            for (file, _, _) in &sources {
                let config = nearest_config(&root, file);
                index.configs.insert((*file).to_string(), config.clone());
                for mode in [ImportMode::Import, ImportMode::Require] {
                    index
                        .resolvers
                        .entry((config.clone(), mode))
                        .or_insert_with(|| {
                            Resolver::new(ResolveOptions {
                                modules: Vec::new(), // No recursive dependency or NODE_PATH lookup.
                                builtin_modules: true,
                                condition_names: vec![
                                    "node".into(),
                                    if mode == ImportMode::Import {
                                        "import"
                                    } else {
                                        "require"
                                    }
                                    .into(),
                                ],
                                extensions: [
                                    ".js", ".mjs", ".cjs", ".ts", ".tsx", ".jsx", ".mts", ".cts",
                                ]
                                .into_iter()
                                .map(str::to_string)
                                .collect(),
                                tsconfig: config.as_ref().map(|p| TsconfigOptions {
                                    config_file: root.join(p),
                                    references: TsconfigReferences::Auto,
                                }),
                                ..ResolveOptions::default()
                            })
                        });
                }
            }
        }
        for (path, language, source) in sources {
            if !parse_exports || !source.contains("export") {
                continue;
            }
            let lang = match language {
                Language::Javascript => SupportLang::JavaScript,
                Language::Tsx => SupportLang::Tsx,
                _ => SupportLang::TypeScript,
            };
            let Ok(doc) = StrDoc::try_new(source, lang) else {
                continue;
            };
            let ast = AstGrep::doc(doc);
            if ast.root().dfs().any(|n| n.is_error() || n.is_missing()) {
                continue;
            }
            index
                .exports
                .insert(path.to_string(), collect_exports(&ast.root()));
        }
        index
    }

    pub(crate) fn is_empty(&self) -> bool {
        self.files.is_empty()
    }

    pub(crate) fn resolve(
        &self,
        importer: &str,
        specifier: &str,
        mode: ImportMode,
    ) -> ModuleTarget {
        let key = (importer.to_string(), specifier.to_string(), mode);
        if let Some(value) = self.cache.lock().unwrap().get(&key).cloned() {
            return value;
        }
        let value = self.resolve_uncached(importer, specifier, mode);
        self.cache.lock().unwrap().insert(key, value.clone());
        value
    }

    fn resolve_uncached(&self, importer: &str, specifier: &str, mode: ImportMode) -> ModuleTarget {
        if specifier.starts_with("node:") {
            return ModuleTarget::External(specifier.to_string());
        }
        let package_name = if specifier.starts_with('@') {
            specifier.split('/').take(2).collect::<Vec<_>>().join("/")
        } else {
            specifier.split('/').next().unwrap_or("").to_string()
        };
        let workspace = self.workspaces.get(&package_name);
        if workspace.is_some_and(Option::is_none) {
            return ModuleTarget::Unresolved("duplicate_workspace_name".into());
        }
        if let Some(root) = &self.root {
            let config = self.configs.get(importer).cloned().flatten();
            let Some(resolver) = self.resolvers.get(&(config, mode)) else {
                return ModuleTarget::Unresolved("importer_not_selected".into());
            };
            let (directory, request) = if let Some(Some(workspace)) = workspace {
                let directory = root.join(&workspace.directory);
                if workspace.exports {
                    (directory, specifier.to_string())
                } else {
                    let request = if specifier == package_name {
                        ".".to_string()
                    } else {
                        format!("./{}", &specifier[package_name.len() + 1..])
                    };
                    (directory, request)
                }
            } else {
                (
                    root.join(importer).parent().unwrap_or(root).to_path_buf(),
                    specifier.to_string(),
                )
            };
            let result = resolver.resolve(&directory, &request).or_else(|error| {
                // Only TS-authored relative imports may refer to emitted JS.
                // Never guess missing package build outputs or export targets.
                if workspace.is_none()
                    && specifier.starts_with('.')
                    && matches!(
                        Path::new(importer).extension().and_then(|v| v.to_str()),
                        Some("ts" | "tsx" | "mts" | "cts")
                    )
                {
                    let substitutions: &[(&str, &str)] = &[
                        (".js", ".ts"),
                        (".js", ".tsx"),
                        (".mjs", ".mts"),
                        (".cjs", ".cts"),
                    ];
                    for (from, to) in substitutions {
                        if let Some(stem) = request.strip_suffix(from)
                            && let Ok(found) = resolver.resolve(&directory, &format!("{stem}{to}"))
                        {
                            return Ok(found);
                        }
                    }
                }
                Err(error)
            });
            if matches!(&result, Err(oxc_resolver::ResolveError::Builtin { .. })) {
                return ModuleTarget::External(specifier.to_string());
            }
            if let Ok(found) = result {
                let target = std::fs::canonicalize(found.path()).ok();
                if let Some(relative) = target
                    .as_ref()
                    .and_then(|path| path.strip_prefix(root).ok())
                {
                    let relative = relative.to_string_lossy().replace('\\', "/");
                    if !relative.split('/').any(|p| p == "node_modules")
                        && self.files.contains(&relative)
                    {
                        return ModuleTarget::Source(relative);
                    }
                }
                return ModuleTarget::Unresolved("outside_selected_sources".into());
            }
            if workspace.is_some()
                || specifier.starts_with('.')
                || specifier.starts_with('#')
                || specifier.starts_with('/')
            {
                return ModuleTarget::Unresolved("target_unavailable_or_not_exported".into());
            }
        } else if specifier.starts_with('.') {
            let base = normalize_relative(importer, specifier);
            if let Some(base) = base {
                let mut candidates = vec![base.clone()];
                for extension in ["ts", "tsx", "js", "jsx", "mts", "cts", "mjs", "cjs"] {
                    candidates.push(format!("{base}.{extension}"));
                    candidates.push(format!("{base}/index.{extension}"));
                }
                if let Some(target) = candidates.into_iter().find(|p| self.files.contains(p)) {
                    return ModuleTarget::Source(target);
                }
            }
            return ModuleTarget::Unresolved("target_unavailable".into());
        }
        ModuleTarget::External(specifier.to_string())
    }

    pub(crate) fn resolve_export(&self, file: &str, name: &str) -> Option<ExportTarget> {
        let key = (file.to_string(), name.to_string());
        if let Some(target) = self.export_cache.lock().unwrap().get(&key).cloned() {
            return target;
        }
        let mut work = 0;
        let mut incomplete = false;
        let target = self.export_inner(
            file,
            name,
            &mut BTreeSet::new(),
            0,
            &mut work,
            &mut incomplete,
        );
        let target = if incomplete { None } else { target };
        if target.is_none() {
            self.export_failures
                .lock()
                .unwrap()
                .insert(format!("{file}#{name}"));
        }
        self.export_cache
            .lock()
            .unwrap()
            .insert(key, target.clone());
        target
    }

    fn export_inner(
        &self,
        file: &str,
        name: &str,
        seen: &mut BTreeSet<(String, String)>,
        depth: usize,
        work: &mut usize,
        incomplete: &mut bool,
    ) -> Option<ExportTarget> {
        *work += 1;
        if depth >= 8 || *work > 256 || !seen.insert((file.to_string(), name.to_string())) {
            *incomplete = true;
            return None;
        }
        let Some(exports) = self.exports.get(file) else {
            *incomplete = true;
            seen.remove(&(file.to_string(), name.to_string()));
            return None;
        };
        let answer = if let Some(edge) = exports.named.get(name) {
            if edge.name.is_empty() {
                seen.remove(&(file.to_string(), name.to_string()));
                return None;
            }
            if let Some(module) = &edge.module {
                if let ModuleTarget::Source(target) = self.resolve(file, module, edge.mode) {
                    self.export_inner(&target, &edge.name, seen, depth + 1, work, incomplete)
                } else {
                    None
                }
            } else {
                Some(ExportTarget {
                    path: file.to_string(),
                    name: edge.name.clone(),
                })
            }
        } else if name != "default" {
            let targets = exports
                .stars
                .iter()
                .filter_map(|module| {
                    if let ModuleTarget::Source(target) =
                        self.resolve(file, module, ImportMode::Import)
                    {
                        self.export_inner(&target, name, seen, depth + 1, work, incomplete)
                    } else {
                        *incomplete = true;
                        None
                    }
                })
                .collect::<BTreeSet<_>>();
            if targets.len() == 1 {
                targets.into_iter().next()
            } else {
                None
            }
        } else {
            None
        };
        seen.remove(&(file.to_string(), name.to_string()));
        answer
    }

    pub(crate) fn export_names(&self, file: &str) -> BTreeSet<String> {
        let mut names = BTreeSet::new();
        let mut queue = vec![(file.to_string(), 0)];
        let mut seen = BTreeSet::new();
        while let Some((file, depth)) = queue.pop() {
            if depth >= 8 || !seen.insert(file.clone()) {
                continue;
            }
            if let Some(exports) = self.exports.get(&file) {
                names.extend(
                    exports
                        .named
                        .keys()
                        .filter(|name| depth == 0 || name.as_str() != "default")
                        .cloned(),
                );
                for module in &exports.stars {
                    if let ModuleTarget::Source(target) =
                        self.resolve(&file, module, ImportMode::Import)
                    {
                        queue.push((target, depth + 1));
                    }
                }
            }
        }
        names
    }

    pub(crate) fn instance_methods(&self, file: &str, constructor: &str) -> BTreeSet<String> {
        self.exports
            .get(file)
            .and_then(|exports| exports.instance_methods.get(constructor))
            .cloned()
            .unwrap_or_default()
    }

    pub(crate) fn diagnostics(&self) -> Vec<String> {
        let cache = self.cache.lock().unwrap();
        let unresolved = cache
            .iter()
            .filter_map(|((from, specifier, _), target)| {
                if let ModuleTarget::Unresolved(reason) = target {
                    Some(format!("{from}: {specifier} ({reason})"))
                } else {
                    None
                }
            })
            .collect::<Vec<_>>();
        let mut messages = Vec::new();
        if !unresolved.is_empty() {
            messages.push(format!("Node module resolution: {} unique unresolved edges; examples: {}. Missing links are not safety verdicts.", unresolved.len(), unresolved.iter().take(8).cloned().collect::<Vec<_>>().join("; ")));
        }
        let exports = self.export_failures.lock().unwrap();
        if !exports.is_empty() {
            messages.push(format!("Node exports: {} unresolved, ambiguous or bounded export lookups; examples: {}. No target was inferred for these lookups.", exports.len(), exports.iter().take(8).cloned().collect::<Vec<_>>().join("; ")));
        }
        messages
    }

    pub(crate) fn trace_metrics(&self) {
        if std::env::var_os("MEHSCAN_TRACE_PHASES").is_none() {
            return;
        }
        let cache = self.cache.lock().unwrap();
        let linked = cache
            .values()
            .filter(|target| matches!(target, ModuleTarget::Source(_)))
            .count();
        let workspace_linked = cache
            .iter()
            .filter(|((_, specifier, _), target)| {
                matches!(target, ModuleTarget::Source(_))
                    && self.workspaces.keys().any(|name| {
                        specifier == name
                            || specifier
                                .strip_prefix(name.as_str())
                                .is_some_and(|rest| rest.starts_with('/'))
                    })
            })
            .count();
        eprintln!(
            "mehscan_node_modules selected_sources={} workspace_packages={} cached_requests={} source_links={} workspace_links={}",
            self.files.len(),
            self.workspaces.len(),
            cache.len(),
            linked,
            workspace_linked
        );
    }
}

fn read_json(path: &Path) -> Option<Value> {
    if std::fs::metadata(path).ok()?.len() > 1024 * 1024 {
        return None;
    }
    serde_json::from_str(&std::fs::read_to_string(path).ok()?).ok()
}
fn workspace_matches(directory: &str, patterns: &[String]) -> bool {
    let matches = |pattern: &str| {
        globset::GlobBuilder::new(pattern)
            .literal_separator(true)
            .build()
            .ok()
            .is_some_and(|glob| glob.compile_matcher().is_match(directory))
    };
    patterns.iter().any(|p| !p.starts_with('!') && matches(p))
        && !patterns
            .iter()
            .any(|p| p.strip_prefix('!').is_some_and(matches))
}
fn nearest_config(root: &Path, file: &str) -> Option<String> {
    let mut directory = root.join(file).parent()?.to_path_buf();
    loop {
        for name in ["tsconfig.json", "jsconfig.json"] {
            if directory.join(name).is_file() {
                return directory
                    .join(name)
                    .strip_prefix(root)
                    .ok()
                    .map(|p| p.to_string_lossy().replace('\\', "/"));
            }
        }
        if directory == root || !directory.pop() || !directory.starts_with(root) {
            return None;
        }
    }
}
fn normalize_relative(importer: &str, specifier: &str) -> Option<String> {
    let mut segments = importer.split('/').collect::<Vec<_>>();
    segments.pop()?;
    for part in specifier.split('/') {
        match part {
            "" | "." => {}
            ".." => {
                segments.pop()?;
            }
            part => segments.push(part),
        }
    }
    Some(segments.join("/"))
}

fn quoted(node: &Node<'_, StrDoc<SupportLang>>) -> Option<String> {
    let text = node.text();
    let quote = text.chars().next()?;
    if !matches!(quote, '\'' | '"') {
        return None;
    }
    text.strip_prefix(quote)?
        .strip_suffix(quote)
        .map(str::to_string)
}
fn collect_exports(root: &Node<'_, StrDoc<SupportLang>>) -> Exports {
    let mut exports = Exports::default();
    for statement in root
        .children()
        .filter(|n| n.kind().as_ref() == "export_statement")
    {
        if statement.children().any(|n| n.kind().as_ref() == "type") {
            continue;
        }
        let module = statement.field("source").and_then(|n| quoted(&n));
        if let Some(clause) = statement
            .children()
            .find(|n| n.kind().as_ref() == "export_clause")
        {
            for specifier in clause
                .children()
                .filter(|n| n.kind().as_ref() == "export_specifier")
            {
                if specifier.children().any(|n| n.kind().as_ref() == "type") {
                    continue;
                }
                let Some(name) = specifier.field("name") else {
                    continue;
                };
                let alias = specifier.field("alias").unwrap_or_else(|| name.clone());
                exports.named.insert(
                    alias.text().into_owned(),
                    ExportEdge {
                        module: module.clone(),
                        name: name.text().into_owned(),
                        mode: ImportMode::Import,
                    },
                );
            }
        } else if let Some(module) = module {
            if statement.children().any(|n| n.kind().as_ref() == "*") {
                exports.stars.push(module);
            }
        } else {
            let default = statement.children().any(|n| n.kind().as_ref() == "default");
            if let Some(declaration) = statement
                .field("declaration")
                .or_else(|| statement.field("value"))
            {
                let names = if let Some(name) = declaration.field("name") {
                    vec![name]
                } else if declaration.kind().as_ref() == "identifier" {
                    vec![declaration]
                } else {
                    declaration
                        .children()
                        .filter(|n| n.kind().as_ref() == "variable_declarator")
                        .filter_map(|n| n.field("name"))
                        .collect()
                };
                for name in names {
                    if name.kind().as_ref() == "identifier" {
                        exports.named.insert(
                            if default {
                                "default".to_string()
                            } else {
                                name.text().into_owned()
                            },
                            ExportEdge {
                                module: None,
                                name: name.text().into_owned(),
                                mode: ImportMode::Import,
                            },
                        );
                    }
                }
            }
        }
    }
    // Preserve Mehscan's existing explicit function-constructor handler model.
    // These are instance members, never module/static exports.
    for function in root
        .dfs()
        .filter(|n| n.kind().as_ref() == "function_declaration")
    {
        let Some(name) = function.field("name") else {
            continue;
        };
        let mut methods = BTreeSet::new();
        for assignment in function
            .dfs()
            .filter(|n| n.kind().as_ref() == "assignment_expression")
        {
            if assignment
                .ancestors()
                .find(|n| {
                    matches!(
                        n.kind().as_ref(),
                        "function_declaration"
                            | "function_expression"
                            | "arrow_function"
                            | "method_definition"
                    )
                })
                .is_none_or(|n| n.range() != function.range())
            {
                continue;
            }
            let (Some(left), Some(right)) = (assignment.field("left"), assignment.field("right"))
            else {
                continue;
            };
            if matches!(
                right.kind().as_ref(),
                "function_expression" | "arrow_function"
            ) && left
                .field("object")
                .is_some_and(|n| n.kind().as_ref() == "this")
                && let Some(property) = left.field("property")
            {
                methods.insert(property.text().into_owned());
            }
        }
        if !methods.is_empty() {
            exports
                .instance_methods
                .insert(name.text().into_owned(), methods);
        }
    }
    for assignment in root.dfs().filter(|n| {
        n.kind().as_ref() == "assignment_expression"
            && !n.ancestors().any(|p| {
                matches!(
                    p.kind().as_ref(),
                    "function_declaration"
                        | "function_expression"
                        | "arrow_function"
                        | "method_definition"
                )
            })
    }) {
        let (Some(left), Some(right)) = (assignment.field("left"), assignment.field("right"))
        else {
            continue;
        };
        let left = left.text();
        if left == "module.exports" && right.kind().as_ref() == "object" {
            for property in right.children().filter(|n| n.is_named()) {
                let key = property.field("key").unwrap_or_else(|| property.clone());
                let value = property.field("value").unwrap_or_else(|| property.clone());
                if matches!(
                    value.kind().as_ref(),
                    "identifier" | "shorthand_property_identifier"
                ) {
                    exports.named.insert(
                        key.text().into_owned(),
                        ExportEdge {
                            module: None,
                            name: value.text().into_owned(),
                            mode: ImportMode::Require,
                        },
                    );
                }
            }
        } else if right.kind().as_ref() == "identifier" {
            let name = left
                .strip_prefix("module.exports.")
                .or_else(|| left.strip_prefix("exports."))
                .or_else(|| (left == "module.exports").then_some("default"));
            if let Some(name) = name {
                exports.named.insert(
                    name.into(),
                    ExportEdge {
                        module: None,
                        name: right.text().into_owned(),
                        mode: ImportMode::Require,
                    },
                );
            }
        }
    }
    // `import { original as local } ...; export { local as publicName }` is
    // another static re-export, not a function body that needs interpretation.
    let mut imported = BTreeMap::new();
    for statement in root
        .children()
        .filter(|n| n.kind().as_ref() == "import_statement")
    {
        let Some(module) = statement.field("source").and_then(|n| quoted(&n)) else {
            continue;
        };
        for specifier in statement
            .dfs()
            .filter(|n| n.kind().as_ref() == "import_specifier")
        {
            let Some(name) = specifier.field("name") else {
                continue;
            };
            let alias = specifier.field("alias").unwrap_or_else(|| name.clone());
            imported.insert(
                alias.text().into_owned(),
                ExportEdge {
                    module: Some(module.clone()),
                    name: name.text().into_owned(),
                    mode: ImportMode::Import,
                },
            );
        }
    }
    for edge in exports.named.values_mut() {
        if edge.module.is_none()
            && let Some(target) = imported.get(&edge.name)
        {
            *edge = target.clone();
        }
    }
    // Observed replacement of a local exported binding makes target identity
    // unresolved. Preserve explicit-export precedence over star exports.
    let replaced = root
        .dfs()
        .filter(|n| {
            matches!(
                n.kind().as_ref(),
                "assignment_expression" | "augmented_assignment_expression"
            ) && !n.ancestors().any(|p| {
                matches!(
                    p.kind().as_ref(),
                    "function_declaration"
                        | "function_expression"
                        | "arrow_function"
                        | "method_definition"
                )
            })
        })
        .filter_map(|n| n.field("left"))
        .filter(|n| n.kind().as_ref() == "identifier")
        .map(|n| n.text().into_owned())
        .collect::<BTreeSet<_>>();
    for edge in exports.named.values_mut() {
        if edge.module.is_none() && replaced.contains(&edge.name) {
            edge.name.clear();
        }
    }
    exports
}
